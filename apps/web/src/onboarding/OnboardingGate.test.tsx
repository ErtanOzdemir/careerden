import { act, cleanup, render, screen } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import type { ApiProfile } from "../api/types.js";
import { OnboardingGate } from "./OnboardingGate.js";

const profileMocks = vi.hoisted(() => ({ me: vi.fn() }));
vi.mock("../api/profiles.js", () => ({
  profileUpdatedEvent: "careerden:profile-updated",
  profilesApi: { me: profileMocks.me },
}));
vi.mock("./OnboardingWizard.js", () => ({
  OnboardingWizard: () => <p>Setup wizard</p>,
}));

function profile(overrides: Partial<ApiProfile> = {}): ApiProfile {
  return {
    id: "profile-1",
    fullName: "",
    email: "",
    autoRunMatchAnalysis: true,
    autoGenerateDocuments: true,
    followUpRemindersEnabled: true,
    certifications: [],
    education: [],
    experience: [],
    links: [],
    projects: [],
    skills: [],
    createdAt: "2026-10-31T00:00:00.000Z",
    updatedAt: "2026-10-31T00:00:00.000Z",
    ...overrides,
  };
}

describe("OnboardingGate", () => {
  beforeEach(() => {
    profileMocks.me.mockReset();
  });
  afterEach(cleanup);

  it("shows the wizard until onboarding is completed", async () => {
    profileMocks.me.mockResolvedValue(profile());

    render(
      <OnboardingGate>
        <p>App shell</p>
      </OnboardingGate>,
    );

    expect(await screen.findByText("Setup wizard")).toBeInTheDocument();
    expect(screen.queryByText("App shell")).not.toBeInTheDocument();

    act(() => {
      window.dispatchEvent(
        new CustomEvent("careerden:profile-updated", {
          detail: profile({ onboardingCompletedAt: "2026-10-31T10:00:00.000Z" }),
        }),
      );
    });

    expect(screen.getByText("App shell")).toBeInTheDocument();
  });

  it("renders the app for profiles that already finished onboarding", async () => {
    profileMocks.me.mockResolvedValue(
      profile({ onboardingCompletedAt: "2026-10-31T10:00:00.000Z" }),
    );

    render(
      <OnboardingGate>
        <p>App shell</p>
      </OnboardingGate>,
    );

    expect(await screen.findByText("App shell")).toBeInTheDocument();
  });

  it("fails open when the profile cannot be read", async () => {
    profileMocks.me.mockRejectedValue(new Error("offline"));

    render(
      <OnboardingGate>
        <p>App shell</p>
      </OnboardingGate>,
    );

    expect(await screen.findByText("App shell")).toBeInTheDocument();
  });
});
