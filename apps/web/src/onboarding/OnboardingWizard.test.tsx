import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import type { ApiProfile } from "../api/types.js";
import { OnboardingWizard, onboardingSteps } from "./OnboardingWizard.js";
import { parseSkills } from "./steps/ProfileBasicsStep.js";

const edition = vi.hoisted(() => ({ local: false }));
vi.mock("../edition.js", () => ({
  get isLocalEdition() {
    return edition.local;
  },
}));
const profileMocks = vi.hoisted(() => ({ update: vi.fn(), updateOnboarding: vi.fn() }));
vi.mock("../api/profiles.js", () => ({
  profileUpdatedEvent: "careerden:profile-updated",
  profilesApi: profileMocks,
}));
vi.mock("./steps/PreferencesStep.js", () => ({ PreferencesStep: () => <p>Preferences</p> }));

const baseProfile: ApiProfile = {
  id: "profile-1",
  fullName: "",
  email: "",
  autoRunMatchAnalysis: true,
  autoGenerateDocuments: true,
  followUpRemindersEnabled: true,
  certifications: [],
  education: [],
  experience: [],
  links: [],
  projects: [],
  skillGroups: [],
  createdAt: "2026-10-31T00:00:00.000Z",
  updatedAt: "2026-10-31T00:00:00.000Z",
};

describe("onboardingSteps", () => {
  it("adds the AI provider step only to the local desktop edition", () => {
    expect(onboardingSteps({ local: true, hasAiBridge: true })).toEqual([
      "welcome",
      "ai-provider",
      "profile",
      "preferences",
      "first-job",
    ]);
    expect(onboardingSteps({ local: true, hasAiBridge: false })).not.toContain("ai-provider");
    expect(onboardingSteps({ local: false, hasAiBridge: true })).not.toContain("ai-provider");
  });
});

describe("parseSkills", () => {
  it("splits, trims, and de-duplicates skills", () => {
    expect(parseSkills("TypeScript, postgres ,typescript,\nGo,")).toEqual([
      "TypeScript",
      "postgres",
      "Go",
    ]);
  });
});

describe("OnboardingWizard", () => {
  beforeEach(() => {
    edition.local = false;
    profileMocks.update.mockReset();
    profileMocks.updateOnboarding.mockReset();
    profileMocks.updateOnboarding.mockResolvedValue({
      ...baseProfile,
      onboardingCompletedAt: "2026-10-31T10:00:00.000Z",
    });
  });
  afterEach(cleanup);

  it("records completion when setup is skipped", async () => {
    const onFinish = vi.fn();
    render(
      <OnboardingWizard profile={baseProfile} onProfileChange={vi.fn()} onFinish={onFinish} />,
    );

    fireEvent.click(screen.getByRole("button", { name: "Skip setup" }));

    await waitFor(() => expect(onFinish).toHaveBeenCalledWith({ openAddJob: false }));
    expect(profileMocks.updateOnboarding).toHaveBeenCalledWith({ completed: true });
  });

  it("requires a name and saves only the changed profile basics", async () => {
    const updated = {
      ...baseProfile,
      fullName: "Ada Lovelace",
      skillGroups: [{ name: "", skills: ["Math"] }],
    };
    profileMocks.update.mockResolvedValue(updated);
    const onProfileChange = vi.fn();
    render(
      <OnboardingWizard
        profile={baseProfile}
        onProfileChange={onProfileChange}
        onFinish={vi.fn()}
      />,
    );

    fireEvent.click(screen.getByRole("button", { name: "Get started" }));
    fireEvent.click(screen.getByRole("button", { name: "Continue" }));
    expect(await screen.findByRole("alert")).toHaveTextContent("Add your name");
    expect(profileMocks.update).not.toHaveBeenCalled();

    fireEvent.change(screen.getByLabelText("Full name"), { target: { value: "Ada Lovelace" } });
    fireEvent.change(screen.getByLabelText("Key skills"), { target: { value: "Math" } });
    fireEvent.click(screen.getByRole("button", { name: "Continue" }));

    expect(await screen.findByText("Preferences")).toBeInTheDocument();
    expect(profileMocks.update).toHaveBeenCalledWith("profile-1", {
      fullName: "Ada Lovelace",
      skillGroups: [{ name: "", skills: ["Math"] }],
    });
    expect(onProfileChange).toHaveBeenCalledWith(updated);
  });

  it("welcomes local users with the privacy promise", () => {
    edition.local = true;
    render(<OnboardingWizard profile={baseProfile} onProfileChange={vi.fn()} onFinish={vi.fn()} />);

    expect(
      screen.getByRole("heading", { name: "Welcome to Careerden Unplugged" }),
    ).toBeInTheDocument();
    expect(screen.getByText("Your data stays on this device")).toBeInTheDocument();
  });
});
