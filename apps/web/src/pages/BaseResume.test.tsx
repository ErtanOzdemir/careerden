import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { MemoryRouter } from "react-router-dom";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import BaseResume from "./BaseResume";

const renderPagedPreview = vi.fn((_html: string, _container: HTMLElement) => ({
  result: Promise.resolve({ totalPages: 1 }),
  cancel: vi.fn(),
  highlightField: vi.fn(),
}));

vi.mock("../lib/paged-preview.js", () => ({
  renderPagedPreview: (html: string, container: HTMLElement) => renderPagedPreview(html, container),
}));

vi.mock("../api/profiles.js", () => ({
  profilesApi: {
    me: vi.fn(),
    update: vi.fn(),
  },
}));

import { profilesApi } from "../api/profiles.js";
import type { ApiProfile } from "../api/types.js";

function renderPage() {
  return render(
    <MemoryRouter>
      <BaseResume />
    </MemoryRouter>,
  );
}

describe("BaseResume", () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  afterEach(() => {
    cleanup();
  });

  it("lists every CV template and previews the selected one", async () => {
    vi.mocked(profilesApi.me).mockResolvedValue(createProfile());
    renderPage();

    const templateNames = ["Classic", "Editorial", "Modern", "Minimal", "Technical", "Ledger"];
    for (const name of templateNames) {
      expect(await screen.findByRole("button", { name: new RegExp(`^${name}`) })).toBeVisible();
    }

    fireEvent.click(screen.getByRole("button", { name: /^Ledger/ }));

    expect(screen.getByRole("heading", { name: "Ledger" })).toBeVisible();
    expect(screen.getByRole("button", { name: /^Ledger/ })).toHaveAttribute("aria-pressed", "true");
    await waitFor(() =>
      expect(renderPagedPreview).toHaveBeenLastCalledWith(
        expect.stringContaining("Ada Lovelace"),
        expect.any(HTMLElement),
      ),
    );
  });

  it("saves the selected template as the profile default", async () => {
    vi.mocked(profilesApi.me).mockResolvedValue(createProfile());
    vi.mocked(profilesApi.update).mockResolvedValue(
      createProfile({ defaultCvTemplateId: "cv.modern" }),
    );
    renderPage();

    fireEvent.click(await screen.findByRole("button", { name: /^Modern/ }));
    fireEvent.click(screen.getByRole("button", { name: "Use as default" }));

    await waitFor(() =>
      expect(profilesApi.update).toHaveBeenCalledWith("profile-1", {
        defaultCvTemplateId: "cv.modern",
      }),
    );
    expect(await screen.findByText("Default")).toBeVisible();
    expect(screen.getByRole("button", { name: /^Modern/ })).toHaveTextContent("In use");
  });

  it("falls back to sample content while the profile is empty", async () => {
    vi.mocked(profilesApi.me).mockResolvedValue(createProfile({ experience: [] }));
    renderPage();

    expect(await screen.findByText(/Showing sample content/)).toBeVisible();
    await waitFor(() =>
      expect(renderPagedPreview).toHaveBeenLastCalledWith(
        expect.stringContaining("Jane Doe"),
        expect.any(HTMLElement),
      ),
    );
  });
});

function createProfile(overrides: Partial<ApiProfile> = {}): ApiProfile {
  return {
    id: "profile-1",
    fullName: "Ada Lovelace",
    email: "ada@example.com",
    autoGenerateDocuments: false,
    autoRunMatchAnalysis: true,
    followUpRemindersEnabled: false,
    certifications: [],
    createdAt: "2026-07-04T00:00:00.000Z",
    education: [],
    experience: [{ company: "Analytical Engines", title: "Programmer" }],
    links: [],
    projects: [],
    skillGroups: [],
    updatedAt: "2026-07-04T00:00:00.000Z",
    ...overrides,
  };
}
