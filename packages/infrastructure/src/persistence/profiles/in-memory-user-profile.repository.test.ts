import { describe, expect, it } from "vitest";
import { InMemoryUserProfileRepository } from "./in-memory-user-profile.repository.js";

describe("InMemoryUserProfileRepository", () => {
  it("updates profile sections without replacing untouched fields", async () => {
    const repository = new InMemoryUserProfileRepository();
    const profile = await repository.create({
      email: "ada@example.com",
      experience: [
        {
          company: "Careerden",
          description: "Built a profile manager",
          title: "Engineer",
        },
      ],
      fullName: "Ada Lovelace",
      headline: "Engineer",
      skillGroups: [{ name: "", skills: ["TypeScript"] }],
    });

    const updated = await repository.update(profile.id, {
      education: [
        {
          degree: "BSc",
          institution: "University",
        },
      ],
      skillGroups: [{ name: "", skills: ["TypeScript", "React"] }],
    });

    expect(updated?.fullName).toBe("Ada Lovelace");
    expect(updated?.experience).toEqual(profile.experience);
    expect(updated?.education).toEqual([{ degree: "BSc", institution: "University" }]);
    expect(updated?.skillGroups).toEqual([{ name: "", skills: ["TypeScript", "React"] }]);
    expect(updated?.updatedAt.getTime()).toBeGreaterThanOrEqual(profile.updatedAt.getTime());
  });

  it("returns null when updating a missing profile", async () => {
    const repository = new InMemoryUserProfileRepository();

    await expect(
      repository.update("missing", { skillGroups: [{ name: "", skills: ["React"] }] }),
    ).resolves.toBeNull();
  });

  it("defaults and updates automatic processing preferences", async () => {
    const repository = new InMemoryUserProfileRepository();
    const profile = await repository.create({
      email: "ada@example.com",
      experience: [],
      fullName: "Ada Lovelace",
      skillGroups: [],
    });

    expect(profile.autoRunMatchAnalysis).toBe(true);
    expect(profile.autoGenerateDocuments).toBe(true);

    const updated = await repository.update(profile.id, {
      autoRunMatchAnalysis: false,
      autoGenerateDocuments: false,
    });

    expect(updated?.autoRunMatchAnalysis).toBe(false);
    expect(updated?.autoGenerateDocuments).toBe(false);
  });

  it("persists default template selection", async () => {
    const repository = new InMemoryUserProfileRepository();
    const profile = await repository.create({
      email: "ada@example.com",
      experience: [],
      fullName: "Ada Lovelace",
      skillGroups: [],
    });

    const updated = await repository.update(profile.id, {
      defaultCvTemplateId: "cv.default",
      defaultCoverLetterTemplateId: "cover-letter.default",
    });

    expect(updated?.defaultCvTemplateId).toBe("cv.default");
    expect(updated?.defaultCoverLetterTemplateId).toBe("cover-letter.default");
  });
});
