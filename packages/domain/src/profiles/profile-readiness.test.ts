import { describe, expect, it } from "vitest";
import type { UserProfile } from "./user-profile.js";
import { assessProfileReadiness } from "./profile-readiness.js";

describe("assessProfileReadiness", () => {
  it("blocks profiles without any career content", () => {
    expect(assessProfileReadiness(createProfile())).toEqual({
      state: "blocked",
      warnings: ["positioning", "skills", "evidence"],
    });
  });

  it("warns while allowing profiles with partial career content", () => {
    expect(assessProfileReadiness(createProfile({ headline: "Software Engineer" }))).toEqual({
      state: "warning",
      warnings: ["skills", "evidence"],
    });
  });

  it("marks profiles with positioning, skills, and evidence as ready", () => {
    expect(
      assessProfileReadiness(
        createProfile({
          headline: "Software Engineer",
          skills: ["TypeScript"],
          projects: [{ name: "Careerden", skills: [], achievements: [] }],
        }),
      ),
    ).toEqual({ state: "ready", warnings: [] });
  });
});

function createProfile(overrides: Partial<UserProfile> = {}): UserProfile {
  const now = new Date("2026-07-14T00:00:00.000Z");
  return {
    id: "profile-1",
    fullName: "Ada Lovelace",
    email: "ada@example.com",
    autoRunMatchAnalysis: true,
    autoGenerateDocuments: true,
    followUpRemindersEnabled: true,
    links: [],
    skills: [],
    experience: [],
    education: [],
    certifications: [],
    projects: [],
    createdAt: now,
    updatedAt: now,
    ...overrides,
  };
}
