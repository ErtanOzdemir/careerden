import { describe, expect, it } from "vitest";
import { createProfileSchema, updateProfileSchema } from "./profile.schema.js";

describe("profile schemas", () => {
  it("defaults auto-run match analysis on for new profiles", () => {
    const result = createProfileSchema.parse({
      fullName: "Ada Lovelace",
      email: "ada@example.com",
    });

    expect(result.autoRunMatchAnalysis).toBe(true);
    expect(result.autoGenerateDocuments).toBe(true);
  });

  it("accepts auto-run match analysis updates", () => {
    const result = updateProfileSchema.parse({
      autoRunMatchAnalysis: false,
    });

    expect(result.autoRunMatchAnalysis).toBe(false);
  });

  it("accepts automatic document generation updates", () => {
    const result = updateProfileSchema.parse({
      autoGenerateDocuments: false,
    });

    expect(result.autoGenerateDocuments).toBe(false);
  });

  it("accepts rich text for summaries and experience and project descriptions", () => {
    const richText = {
      version: 1 as const,
      blocks: [
        {
          type: "paragraph" as const,
          children: [{ type: "text" as const, text: "Built reliable systems" }],
        },
      ],
    };

    const result = updateProfileSchema.parse({
      summaryRichText: richText,
      experience: [
        {
          company: "Careerden",
          title: "Engineer",
          descriptionRichText: richText,
        },
      ],
      projects: [
        {
          name: "Careerden",
          descriptionRichText: richText,
          skills: [],
          achievements: [],
        },
      ],
    });

    expect(result.summaryRichText).toEqual(richText);
    expect(result.experience?.[0]?.descriptionRichText).toEqual(richText);
    expect(result.projects?.[0]?.descriptionRichText).toEqual(richText);
  });
});
