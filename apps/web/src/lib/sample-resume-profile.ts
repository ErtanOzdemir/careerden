import type { ApiProfile, RichDocument } from "../api/types.js";

function bullets(...lines: string[]): RichDocument {
  return {
    version: 1,
    blocks: [
      {
        type: "bulletList",
        items: lines.map((text) => ({
          blocks: [{ type: "paragraph", children: [{ type: "text", text }] }],
        })),
      },
    ],
  };
}

