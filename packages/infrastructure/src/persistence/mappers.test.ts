import { describe, expect, it } from "vitest";
import { richDocumentFromText } from "@careerden/domain";
import { toJobApplication, toUserProfile } from "./mappers.js";

describe("toUserProfile", () => {
  it("preserves stored rich profile content and upgrades legacy descriptions", () => {
    const summaryRichText = richDocumentFromText("Formatted summary");
    const profile = toUserProfile({
      id: "profile-1",
      full_name: "Ada Lovelace",
      email: "ada@example.com",
      summary: "Formatted summary",
      summary_rich_text: summaryRichText,
      links: [],
      skill_groups: [],
      experience: [
        {
          company: "Analytical Engines",
          title: "Engineer",
          description: "Legacy experience description",
        },
      ],
      education: [],
      certifications: [],
      projects: [
        {
          name: "Careerden",
          description: "Legacy project description",
          skills: [],
          achievements: [],
        },
      ],
      created_at: "2026-07-13T00:00:00.000Z",
      updated_at: "2026-07-13T00:00:00.000Z",
    });

    expect(profile.summaryRichText).toEqual(summaryRichText);
    expect(profile.experience[0]?.descriptionRichText).toEqual(
      richDocumentFromText("Legacy experience description"),
    );
    expect(profile.projects[0]?.descriptionRichText).toEqual(
      richDocumentFromText("Legacy project description"),
    );
    expect(profile.autoGenerateDocuments).toBe(true);
  });
});

describe("toJobApplication", () => {
  it("maps stored application-pack preferences and upgrades legacy rows to defaults", () => {
    const base = {
      id: "job-1",
      profile_id: "profile-1",
      status: "queued",
      application_status: "saved",
      tags: [],
      metadata: {},
      created_at: "2026-07-14T00:00:00.000Z",
      updated_at: "2026-07-14T00:00:00.000Z",
    };

    expect(toJobApplication(base).applicationPackPreferences).toEqual({
      language: "auto",
      tone: "professional",
    });
    expect(
      toJobApplication({
        ...base,
        application_pack_preferences: {
          language: "tr-TR",
          tone: "creative",
          cvTemplateId: "cv-template",
        },
      }).applicationPackPreferences,
    ).toEqual({ language: "tr-TR", tone: "creative", cvTemplateId: "cv-template" });
  });
});
