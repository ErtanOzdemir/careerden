import { z } from "zod";
import { richDocumentSchema } from "../documents/rich-document.schema.js";
import {
  getHtmlTemplateById,
  isHttpProfileLinkUrl,
  MAX_PROFILE_LINKS,
  PROFILE_LINK_KINDS,
} from "@careerden/contracts";

export const profileExperienceSchema = z.object({
  company: z.string().min(1),
  title: z.string().min(1),
  startDate: z.string().optional(),
  endDate: z.string().optional(),
  description: z.string().optional(),
  descriptionRichText: richDocumentSchema.optional(),
});

export const profileEducationSchema = z.object({
  institution: z.string().min(1),
  degree: z.string().optional(),
  field: z.string().optional(),
  startDate: z.string().optional(),
  endDate: z.string().optional(),
  description: z.string().optional(),
  descriptionRichText: richDocumentSchema.optional(),
});

export const profileProjectSchema = z.object({
  name: z.string().min(1),
  description: z.string().optional(),
  descriptionRichText: richDocumentSchema.optional(),
  url: z.string().url().optional(),
  skills: z.array(z.string().min(1)).default([]),
  achievements: z.array(z.string().min(1)).default([]),
});

/**
 * A typed profile link. The URL becomes an `href` in rendered CVs, so only absolute `http:` and
 * `https:` URLs are accepted; `javascript:`, `data:`, `mailto:`, and other schemes are refused.
 */
export const profileLinkSchema = z.object({
  kind: z.enum(PROFILE_LINK_KINDS),
  url: z
    .string()
    .trim()
    .max(2048)
    .url()
    .refine(isHttpProfileLinkUrl, { message: "Links must be http or https URLs" }),
});

export const profileLinksSchema = z.array(profileLinkSchema).max(MAX_PROFILE_LINKS);

/**
 * A phone number kept as free text so international formats work: digits, spaces, and `+ - ( ) .`
 * only, with at least one digit. An empty string clears the stored number. Both patterns are a
 * single character class or a single character, so matching stays linear in the input length.
 */
export const profilePhoneSchema = z
  .string()
  .trim()
  .max(40)
  .regex(/^[\d +\-().]*$/, "Phone may contain only digits, spaces, and + - ( ) .")
  .refine((value) => value === "" || /\d/.test(value), "Phone must contain a digit");

/** A skill category; an empty name holds uncategorized skills. */
export const profileSkillGroupSchema = z.object({
  name: z.string(),
  skills: z.array(z.string().min(1)),
});

// The profile fields without creation defaults. Updates are built from this shape, never from
// `profileObjectSchema`: zod 4 still applies an inner `.default()` under `.partial()`, so a PATCH
// that sends one field would reset every omitted list to [] and every toggle to true.
const profileFieldsSchema = z.object({
  fullName: z.string().min(1),
  email: z.string().email(),
  phone: profilePhoneSchema.optional(),
  autoRunMatchAnalysis: z.boolean(),
  autoGenerateDocuments: z.boolean(),
  followUpRemindersEnabled: z.boolean(),
  profession: z.string().optional(),
  headline: z.string().optional(),
  location: z.string().optional(),
  links: profileLinksSchema,
  summary: z.string().optional(),
  summaryRichText: richDocumentSchema.optional(),
  skillGroups: z.array(profileSkillGroupSchema),
  experience: z.array(profileExperienceSchema),
  education: z.array(profileEducationSchema),
  certifications: z.array(z.string().min(1)),
  projects: z.array(profileProjectSchema),
  defaultCvTemplateId: z.string().min(1).optional(),
  defaultCoverLetterTemplateId: z.string().min(1).optional(),
});

const { shape } = profileFieldsSchema;

const profileObjectSchema = profileFieldsSchema.extend({
  autoRunMatchAnalysis: shape.autoRunMatchAnalysis.default(true),
  autoGenerateDocuments: shape.autoGenerateDocuments.default(true),
  followUpRemindersEnabled: shape.followUpRemindersEnabled.default(true),
  links: shape.links.default([]),
  skillGroups: shape.skillGroups.default([]),
  experience: shape.experience.default([]),
  education: shape.education.default([]),
  certifications: shape.certifications.default([]),
  projects: shape.projects.default([]),
});

function validateTemplateSelection(
  value: { defaultCvTemplateId?: string; defaultCoverLetterTemplateId?: string },
  context: z.RefinementCtx,
): void {
  if (value.defaultCvTemplateId) {
    const template = getHtmlTemplateById(value.defaultCvTemplateId);
    if (!template || template.kind !== "cv") {
      context.addIssue({
        code: z.ZodIssueCode.custom,
        path: ["defaultCvTemplateId"],
        message: "Unknown CV template",
      });
    }
  }
  if (value.defaultCoverLetterTemplateId) {
    const template = getHtmlTemplateById(value.defaultCoverLetterTemplateId);
    if (!template || template.kind !== "cover_letter") {
      context.addIssue({
        code: z.ZodIssueCode.custom,
        path: ["defaultCoverLetterTemplateId"],
        message: "Unknown cover letter template",
      });
    }
  }
}

export const createProfileSchema = profileObjectSchema.superRefine(validateTemplateSelection);
export const updateProfileSchema = profileFieldsSchema
  .partial()
  .superRefine(validateTemplateSelection);

export type CreateProfileDto = z.infer<typeof createProfileSchema>;
export type UpdateProfileDto = z.infer<typeof updateProfileSchema>;

export const updateOnboardingStateSchema = z
  .object({
    completed: z.boolean().optional(),
    checklistDismissed: z.boolean().optional(),
  })
  .strict()
  .refine((value) => value.completed !== undefined || value.checklistDismissed !== undefined, {
    message: "Provide completed or checklistDismissed",
  });

export type UpdateOnboardingStateDto = z.infer<typeof updateOnboardingStateSchema>;
