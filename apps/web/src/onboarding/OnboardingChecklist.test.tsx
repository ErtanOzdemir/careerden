import { cleanup, fireEvent, render, screen } from "@testing-library/react";
import { MemoryRouter } from "react-router-dom";
import { afterEach, describe, expect, it, vi } from "vitest";
import type { ApiProfile } from "../api/types.js";
import { OnboardingChecklist, buildChecklistItems } from "./OnboardingChecklist.js";

vi.mock("../edition.js", () => ({ isLocalEdition: false }));
const profileMocks = vi.hoisted(() => ({ updateOnboarding: vi.fn(async () => ({})) }));
vi.mock("../api/profiles.js", () => ({
  profileUpdatedEvent: "careerden:profile-updated",
  profilesApi: profileMocks,
}));

const profile: ApiProfile = {
  id: "profile-1",
  fullName: "Ada Lovelace",
  email: "ada@example.com",
  autoRunMatchAnalysis: true,
  autoGenerateDocuments: true,
  followUpRemindersEnabled: true,
  certifications: [],
  education: [],
  experience: [],
  links: [],
  projects: [],
  skillGroups: [],
  defaultCvTemplateId: "cv.default",
  createdAt: "2026-10-31T00:00:00.000Z",
  updatedAt: "2026-10-31T00:00:00.000Z",
};

describe("buildChecklistItems", () => {
  it("derives each item from the user's data", () => {
    const items = buildChecklistItems({
      profile,
      hasApplications: false,
      aiProviderConfigured: false,
    });

    expect(items.map((item) => [item.id, item.done])).toEqual([
      ["ai-provider", false],
      ["profile", false],
      ["template", true],
      ["first-job", false],
    ]);
  });

  it("omits the AI provider item outside the local desktop app", () => {
    const items = buildChecklistItems({
      profile,
      hasApplications: true,
      aiProviderConfigured: null,
    });

    expect(items.map((item) => item.id)).not.toContain("ai-provider");
  });
});

describe("OnboardingChecklist", () => {
  afterEach(cleanup);

  it("stays hidden once every item is done", () => {
    render(
      <MemoryRouter>
        <OnboardingChecklist
          profile={{
            ...profile,
            experience: [{ company: "Analytical Engines", title: "Programmer" }],
          }}
          hasApplications
        />
      </MemoryRouter>,
    );

    expect(screen.queryByText("Finish setting up Careerden")).not.toBeInTheDocument();
  });

  it("records a dismissal and hides the card", () => {
    render(
      <MemoryRouter>
        <OnboardingChecklist profile={profile} hasApplications={false} />
      </MemoryRouter>,
    );

    expect(screen.getByText("1 of 3 done")).toBeInTheDocument();
    fireEvent.click(screen.getByRole("button", { name: "Dismiss setup checklist" }));

    expect(screen.queryByText("Finish setting up Careerden")).not.toBeInTheDocument();
    expect(profileMocks.updateOnboarding).toHaveBeenCalledWith({ checklistDismissed: true });
  });
});
