import { cleanup, render, screen } from "@testing-library/react";
import { afterEach, describe, expect, it, vi } from "vitest";
import Settings from "./Settings";

vi.mock("../edition.js", () => ({ isLocalEdition: true }));
const authMocks = vi.hoisted(() => ({
  useSession: vi.fn(),
  useAccountSession: vi.fn(() => ({ data: null, isPending: false, refetch: vi.fn() })),
}));
vi.mock("../api/auth.js", () => ({
  accountEmailApi: { confirmChange: vi.fn(), requestChange: vi.fn() },
  authClient: { changePassword: vi.fn(), useSession: authMocks.useSession },
  useAccountSession: authMocks.useAccountSession,
}));
vi.mock("../api/profiles.js", () => ({
  profilesApi: {
    me: vi.fn(async () => ({
      id: "profile-1",
      fullName: "Ada Lovelace",
      email: "local@careerden.local",
      autoRunMatchAnalysis: true,
      autoGenerateDocuments: true,
      followUpRemindersEnabled: true,
      certifications: [],
      education: [],
      experience: [],
      links: [],
      projects: [],
      skills: [],
      createdAt: "2026-10-29T00:00:00.000Z",
      updatedAt: "2026-10-29T00:00:00.000Z",
    })),
    update: vi.fn(),
  },
}));

describe("Settings in the local edition", () => {
  afterEach(cleanup);

  it("omits account and security settings and never reads an account session", async () => {
    render(<Settings />);

    expect(await screen.findByText("Processing preferences")).toBeInTheDocument();
    expect(screen.queryByRole("heading", { name: "Account" })).not.toBeInTheDocument();
    expect(screen.queryByRole("heading", { name: "Security" })).not.toBeInTheDocument();
    expect(authMocks.useSession).not.toHaveBeenCalled();
  });
});
