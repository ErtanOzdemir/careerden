import { describe, expect, it } from "vitest";
import type { UserProfile } from "@careerden/domain";
import { mergeProfileImport } from "./profile-import.js";

function profile(overrides: Partial<UserProfile> = {}): UserProfile {
  const now = new Date("2026-01-01T00:00:00.000Z");
  return {
    id: "profile-1",
    fullName: "",
    email: "",
    autoRunMatchAnalysis: true,
    autoGenerateDocuments: true,
    followUpRemindersEnabled: true,
    links: [],
    skills: [],
    experience: [],
    education: [],
    certifications: [],
    projects: [],
    createdAt: now,
    updatedAt: now,
    ...overrides,
  };
}

describe("mergeProfileImport", () => {
  it("fills empty single-value fields and keeps the ones the user wrote", () => {
    const update = mergeProfileImport(profile({ fullName: "Ada Lovelace", headline: " " }), {
      fullName: "A. Lovelace",
      email: "ada@example.com",
      headline: "Analyst",
    });

    expect(update).toEqual({ email: "ada@example.com", headline: "Analyst" });
  });

  it("appends list entries the profile does not have yet", () => {
    const update = mergeProfileImport(
      profile({
        skills: ["TypeScript"],
        links: ["https://www.linkedin.com/in/ada/"],
        experience: [{ company: "Analytical Engines", title: "Engineer" }],
      }),
      {
        skills: ["typescript", "PostgreSQL", "postgresql"],
        links: ["https://linkedin.com/in/ada", "https://github.com/ada"],
        experience: [
          { company: "analytical engines", title: "Engineer " },
          { company: "Babbage & Co", title: "Translator" },
        ],
      },
    );

    expect(update).toEqual({
      skills: ["TypeScript", "PostgreSQL"],
      links: ["https://www.linkedin.com/in/ada/", "https://github.com/ada"],
      experience: [
        { company: "Analytical Engines", title: "Engineer" },
        { company: "Babbage & Co", title: "Translator" },
      ],
    });
  });

  it("returns no changes when the draft adds nothing", () => {
    expect(
      mergeProfileImport(profile({ fullName: "Ada", projects: [project("Engine")] }), {
        fullName: "Ada",
        projects: [project("engine")],
      }),
    ).toEqual({});
  });
});

function project(name: string) {
  return { name, skills: [], achievements: [] };
}
