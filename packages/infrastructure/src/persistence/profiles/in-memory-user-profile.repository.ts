import type { CreateUserProfileInput, UpdateUserProfileInput, UserProfile, UserProfileRepository } from "@careerden/domain";
import { randomUUID } from "node:crypto";

export class InMemoryUserProfileRepository implements UserProfileRepository {
  private readonly profiles = new Map<string, UserProfile>();

  async create(input: CreateUserProfileInput): Promise<UserProfile> {
    const now = new Date();
    const profile: UserProfile = {
      id: randomUUID(),
      ...input,
      autoRunMatchAnalysis: input.autoRunMatchAnalysis ?? true,
      autoGenerateDocuments: input.autoGenerateDocuments ?? true,
      followUpRemindersEnabled: input.followUpRemindersEnabled ?? true,
      links: input.links ?? [],
      education: input.education ?? [],
      certifications: input.certifications ?? [],
      projects: input.projects ?? [],
      createdAt: now,
      updatedAt: now,
    };

    this.profiles.set(profile.id, profile);
    return profile;
  }

  async findById(id: string): Promise<UserProfile | null> {
    return this.profiles.get(id) ?? null;
  }

  async update(id: string, input: UpdateUserProfileInput): Promise<UserProfile | null> {
    const existing = this.profiles.get(id);

    if (!existing) {
      return null;
    }

    const updated: UserProfile = {
      ...existing,
      ...input,
      education: input.education ?? existing.education,
      certifications: input.certifications ?? existing.certifications,
      projects: input.projects ?? existing.projects,
      updatedAt: new Date(),
    };

    this.profiles.set(id, updated);
    return updated;
  }
}
