import type {
  JobApplicationQueuePayload,
  JobApplicationRepository,
  PersistenceUnitOfWork,
  UserProfileRepository,
} from "@careerden/domain";
import { assessProfileReadiness, documentContentFromProfile } from "@careerden/domain";
import { ApplicationError } from "@careerden/application";
import type { ExtractJobRequirementsUseCase } from "../matching/extract-job-requirements.use-case.js";
import type { RunMatchAnalysisUseCase } from "@careerden/application";
import { enqueueApplicationPackGeneration } from "@careerden/application";
import { validateApplicationPackPreferences } from "@careerden/application";

export class AnalyzeScrapedJobUseCase {
  constructor(
    private readonly jobApplications: JobApplicationRepository,
    private readonly profiles: UserProfileRepository,
    private readonly matching: RunMatchAnalysisUseCase,
    private readonly unitOfWork: PersistenceUnitOfWork,
    private readonly extractRequirements?: Pick<ExtractJobRequirementsUseCase, "execute">,
  ) {}

  async execute(payload: JobApplicationQueuePayload): Promise<void> {
    const jobApplication = await this.jobApplications.findById(payload.jobApplicationId);

    if (!jobApplication) {
      throw new ApplicationError(
        "not_found",
        `Job application ${payload.jobApplicationId} was not found`,
      );
    }
    const attemptId = payload.analysisAttemptId;
    const started = await this.unitOfWork.execute(
      async ({ credits, jobApplications, jobApplicationChanges }): Promise<boolean> => {
        const reservation = await credits.findReservation(attemptId);
        if (!reservation || reservation.status !== "reserved") return false;
        const begin = await jobApplications.beginAnalysis(jobApplication.id, attemptId);
        if (!begin.accepted) {
          await credits.releaseReservation(attemptId, "superseded", new Date());
          return false;
        }
        if (begin.started) {
          await jobApplications.addEvent({
            jobApplicationId: jobApplication.id,
            type: "processing",
            title: "AI analysis started",
            metadata: { attemptId },
          });
          await jobApplicationChanges.changed(jobApplication.id, jobApplication.profileId);
        }
        return true;
      },
    );
    if (!started) return;

    const profile = await this.profiles.findById(jobApplication.profileId);

    if (!profile) {
      throw new ApplicationError("not_found", `Profile ${jobApplication.profileId} was not found`);
    }

    let scrape = await this.jobApplications.getScrapeBundle(jobApplication.id);

    if (!scrape) {
      throw new ApplicationError(
        "validation",
        `No desktop scrape bundle found for job application ${jobApplication.id}`,
      );
    }

    if (scrape.job.requirements.length === 0 && this.extractRequirements) {
      const job = await this.extractRequirements.execute({
        jobApplicationId: jobApplication.id,
        job: scrape.job,
      });
      scrape = { ...scrape, job };
      await this.unitOfWork.execute(async ({ jobApplications, jobApplicationChanges }) => {
        await jobApplications.saveScrapeBundle(jobApplication.id, scrape!);
        await jobApplications.addEvent({
          jobApplicationId: jobApplication.id,
          type: "processing",
          title: "Job requirements extracted",
          metadata: { requirementCount: job.requirements.length },
        });
        await jobApplicationChanges.changed(jobApplication.id, jobApplication.profileId);
      });
    }

    const analysis = await this.matching.execute({
      jobApplicationId: jobApplication.id,
      profile,
      scrape,
      applicationPackPreferences: jobApplication.applicationPackPreferences,
    });

    await this.unitOfWork.execute(
      async ({ credits, jobApplications, jobApplicationChanges, outbox }) => {
        const completed = await jobApplications.completeAnalysis(
          jobApplication.id,
          attemptId,
          analysis,
          documentContentFromProfile(profile, analysis),
        );
        if (!completed) {
          await credits.releaseReservation(attemptId, "superseded", new Date());
          return;
        }
        if (!(await credits.consumeReservation(attemptId, new Date()))) {
          throw new Error(`Credit reservation ${attemptId} could not be consumed`);
        }
        await jobApplications.addEvent({
          jobApplicationId: jobApplication.id,
          type: "processing",
          title: "AI analysis completed",
          metadata: { matchScore: analysis.matchScore, attemptId },
        });
        let generationQueued = false;
        if (profile.autoGenerateDocuments && assessProfileReadiness(profile).state !== "blocked") {
          try {
            validateApplicationPackPreferences(jobApplication.applicationPackPreferences);
            generationQueued = Boolean(
              await enqueueApplicationPackGeneration({
                jobApplications,
                outbox,
                jobApplication,
              }),
            );
          } catch (error) {
            if (!(error instanceof ApplicationError)) throw error;
            await jobApplications.addEvent({
              jobApplicationId: jobApplication.id,
              type: "processing",
              title: "Application pack needs attention",
              body: error.message,
            });
          }
        }
        if (!generationQueued) {
          await jobApplications.addEvent({
            jobApplicationId: jobApplication.id,
            type: "processing",
            title: "Ready for AI match review",
            metadata: { matchScore: analysis.matchScore, attemptId },
          });
        }
        await jobApplicationChanges.changed(jobApplication.id, jobApplication.profileId);
      },
    );
  }
}
