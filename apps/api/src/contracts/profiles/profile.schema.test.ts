import { describe, expect, it } from "vitest";
import { createProfileSchema, updateProfileSchema } from "./profile.schema.js";

describe("profile schemas", () => {
  it("defaults auto-run match analysis on for new profiles", () => {
    const result = createProfileSchema.parse({
      fullName: "Ada Lovelace",
      email: "ada@example.com",
    });

    expect(result.autoRunMatchAnalysis).toBe(true);
    expect(result.autoGenerateDocuments).toBe(true);
  });

  it("accepts auto-run match analysis updates", () => {
    const result = updateProfileSchema.parse({
      autoRunMatchAnalysis: false,
    });

    expect(result.autoRunMatchAnalysis).toBe(false);
  });

  it("leaves fields an update omits out of the result instead of defaulting them", () => {
    expect(updateProfileSchema.parse({ autoRunMatchAnalysis: false })).toEqual({
      autoRunMatchAnalysis: false,
    });
    expect(updateProfileSchema.parse({ phone: "+1 555 0100" })).toEqual({ phone: "+1 555 0100" });
    expect(updateProfileSchema.parse({ defaultCvTemplateId: "cv.modern" })).toEqual({
      defaultCvTemplateId: "cv.modern",
    });
  });

  it("still defaults lists and toggles when a profile is created", () => {
    expect(
      createProfileSchema.parse({ fullName: "Ada Lovelace", email: "ada@example.com" }),
    ).toMatchObject({
      followUpRemindersEnabled: true,
      links: [],
      skillGroups: [],
      experience: [],
      education: [],
      certifications: [],
      projects: [],
    });
  });

  it("accepts international phone formats as trimmed free text", () => {
    for (const phone of ["+44 20 7946 0958", "(555) 010-0100", "+90 (212) 555.01.01"]) {
      expect(updateProfileSchema.parse({ phone: ` ${phone} ` }).phone).toBe(phone);
    }
  });

  it("accepts an empty phone so the stored number can be cleared", () => {
    expect(updateProfileSchema.parse({ phone: "  " }).phone).toBe("");
  });

  it("rejects phones with letters, without digits, or longer than 40 characters", () => {
    for (const phone of ["call me", "555-0100 ext. 2", "+-()", "555\n0100", "1".repeat(41)]) {
      expect(updateProfileSchema.safeParse({ phone }).success).toBe(false);
    }
  });

  it("checks long phone input in linear time", () => {
    const started = performance.now();
    expect(updateProfileSchema.safeParse({ phone: `${"1 ".repeat(125_000)}x` }).success).toBe(
      false,
    );
    expect(performance.now() - started).toBeLessThan(1_000);
  });

  it("accepts automatic document generation updates", () => {
    const result = updateProfileSchema.parse({
      autoGenerateDocuments: false,
    });

    expect(result.autoGenerateDocuments).toBe(false);
  });

  it("accepts typed http and https links", () => {
    const links = [
      { kind: "linkedin", url: "https://www.linkedin.com/in/ada" },
      { kind: "portfolio", url: "http://ada.example.com/work" },
    ];

    expect(updateProfileSchema.parse({ links }).links).toEqual(links);
  });

  it.each([
    [["https://github.com/ada"]],
    [[{ kind: "github" }]],
    [[{ kind: "blog", url: "https://ada.dev" }]],
    [[{ kind: "website", url: "ada.dev" }]],
    [[{ kind: "website", url: "javascript:alert(1)" }]],
    [[{ kind: "website", url: "data:text/html,hi" }]],
    [[{ kind: "website", url: "mailto:ada@example.com" }]],
    [[{ kind: "website", url: "ftp://ada.dev" }]],
    [
      Array.from({ length: 11 }, (_value, index) => ({
        kind: "website",
        url: `https://a${index}.dev`,
      })),
    ],
  ])("rejects invalid links %#", (links) => {
    expect(updateProfileSchema.safeParse({ links }).success).toBe(false);
  });

  it("accepts rich text for summaries and experience and project descriptions", () => {
    const richText = {
      version: 1 as const,
      blocks: [
        {
          type: "paragraph" as const,
          children: [{ type: "text" as const, text: "Built reliable systems" }],
        },
      ],
    };

    const result = updateProfileSchema.parse({
      summaryRichText: richText,
      experience: [
        {
          company: "Careerden",
          title: "Engineer",
          descriptionRichText: richText,
        },
      ],
      projects: [
        {
          name: "Careerden",
          descriptionRichText: richText,
          skills: [],
          achievements: [],
        },
      ],
    });

    expect(result.summaryRichText).toEqual(richText);
    expect(result.experience?.[0]?.descriptionRichText).toEqual(richText);
    expect(result.projects?.[0]?.descriptionRichText).toEqual(richText);
  });
});
